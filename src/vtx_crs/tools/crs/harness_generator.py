"""Generate fuzz/PoC harnesses for target functions or binaries.

Creates minimal harness code that calls a target function with structured
inputs. The model is expected to compile and run the harness under a fuzzer.
"""

from __future__ import annotations

import asyncio
from pathlib import Path

from pydantic import BaseModel
from vtx.core.types import ToolResult
try:
    from vtx.coding_agent.tools import BaseTool  # legacy
    from vtx.core.types import ToolResult  # legacy
except (ModuleNotFoundError, ImportError):
    from vtx.tools import BaseTool  # type: ignore
    from vtx.core.types import ToolResult

from vtx_crs.core import get_case_manager

from ._common import resolve_repo_path

_case_manager = get_case_manager()


class HarnessGenParams(BaseModel):
    repo_path: str = ""
    target_file: str = ""
    target_function: str = ""
    language: str = "python"
    output_path: str = ""
    poc_type: str = "python"  # python | c | rust


class HarnessGeneratorTool(BaseTool[HarnessGenParams]):
    name = "harness_gen"
    description = (
        "Generate a minimal fuzz/PoC harness for a target function or binary entry "
        "point. The harness is written to disk and can be built and run under the "
        "project's fuzzer or test runner."
    )
    params = HarnessGenParams
    mutating = True
    prompt_guidelines = (
        "Run harness_gen after vuln_scan or crash_triage to turn a sink into a runnable target.",
        "Use the harness with build_runner and test_runner to reproduce the issue.",
        "Iterate: update the harness based on crash output from fuzz_harness.",
    )

    async def execute(
        self, params: HarnessGenParams, cancel_event: asyncio.Event | None = None
    ) -> ToolResult:
        repo = resolve_repo_path(params.repo_path, _case_manager.active_case.repo_path)

        target = params.target_function or Path(params.target_file).stem or "target"
        poc_type = params.poc_type.lower()
        # Map poc_type to real file extension (fix: "python" -> "py")
        ext_map = {"python": "py", "py": "py", "c": "c", "rust": "rs", "rs": "rs", "go": "go", "js": "js"}
        ext = ext_map.get(poc_type, poc_type if "." not in poc_type else poc_type.split(".")[-1])
        # Language-aware default
        lang_ext = {"python": "py", "c": "c", "rust": "rs", "go": "go", "js": "js"}.get(params.language.lower(), ext)
        final_ext = ext if poc_type in ext_map else lang_ext
        output_path = Path(params.output_path) if params.output_path else repo / "harness" / f"harness_{target}.{final_ext}"
        output_path.parent.mkdir(parents=True, exist_ok=True)

        content = self._render(target, params.target_file, poc_type)

        try:
            output_path.write_text(content, encoding="utf-8")
        except OSError as exc:
            return ToolResult(
                success=False,
                result=f"Failed to write harness: {exc}",
                ui_summary="Harness write failed",
                ui_details="",
            )

        result_text = (
            f"Harness written to: {output_path}\n\n"
            "Next steps:\n"
            f"  1. Inspect the harness.\n"
            f"  2. Build it: build_runner(build_command='python {output_path.name}' or equivalent).\n"
            f"  3. Fuzz: fuzz_harness with the harness as the seed corpus."
        )
        return ToolResult(
            success=True,
            result=result_text,
            ui_summary=f"Harness generated: {output_path.name}",
            ui_details=result_text,
        )

    @staticmethod
    def _render(target: str, target_file: str, poc_type: str) -> str:
        # Defensive+Offensive: produce actionable harnesses that actually import/call target (RAPTOR-style)
        safe_target = target.replace("-", "_").replace(".", "_")
        if poc_type == "python":
            return (
                f'"""Fuzz harness for {target} — auto-generated by vtx-crs (offensive+defensive)."""\n'
                f'"""Tests {target_file} with AFL/libFuzzer-style entry."""\n\n'
                f"import sys\nfrom pathlib import Path\n\n"
                f"# --- attempt to import target module ---\n"
                f"import importlib.util\n\n"
                f"def _load_target():\n"
                f"    tf = Path(r\"{target_file}\")\n"
                f"    if tf.exists():\n"
                f"        spec = importlib.util.spec_from_file_location(\"_target\", tf)\n"
                f"        if spec and spec.loader:\n"
                f"            m = importlib.util.module_from_spec(spec)\n"
                f"            try:\n"
                f"                spec.loader.exec_module(m)  # type: ignore\n"
                f"                return m\n"
                f"            except Exception as e:\n"
                f"                print(f'[harness] import failed: {{e}}', file=sys.stderr)\n"
                f"    return None\n\n"
                f"_mod = _load_target()\n"
                f"_fn = getattr(_mod, \"{safe_target}\", None) if _mod else None\n\n"
                f"def LLVMFuzzerTestOneInput(data: bytes) -> int:\n"
                f"    '''AFL/libFuzzer entry point — feed mutated input to target.'''\n"
                f"    inp = data.decode('utf-8', errors='ignore')\n"
                f"    if _fn and callable(_fn):\n"
                f"        try:\n"
                f"            # Try common signatures\n"
                f"            try:\n"
                f"                _fn(inp)\n"
                f"            except TypeError:\n"
                f"                _fn(inp.encode())\n"
                f"        except Exception:\n"
                f"            pass  # crash will be caught by fuzzer\n"
                f"    return 0\n\n"
                f"def main() -> int:\n"
                f"    import argparse\n"
                f"    p = argparse.ArgumentParser(description='Harness for {target}')\n"
                f"    p.add_argument('input', nargs='?', default='')\n"
                f"    p.add_argument('--stdin', action='store_true', help='read from stdin')\n"
                f"    a = p.parse_args()\n"
                f"    data = sys.stdin.buffer.read() if a.stdin else a.input.encode()\n"
                f"    return LLVMFuzzerTestOneInput(data)\n\n\n"
                f"if __name__ == '__main__':\n"
                f"    sys.exit(main())\n"
            )
        if poc_type == "c":
            return (
                f'/* Fuzz harness for {target} — vtx-crs offensive+defensive. */\n'
                f'/* Compile: clang -g -O1 -fsanitize=fuzzer,address -o harness harness_{safe_target}.c {target_file} */\n\n'
                f"#include <stdint.h>\n#include <stddef.h>\n#include <stdio.h>\n#include <string.h>\n#include <stdlib.h>\n\n"
                f"/* Target prototype — adjust after inspecting {target_file} */\n"
                f"extern int {safe_target}(const char *input);\n"
                f"__attribute__((weak)) int {safe_target}(const char *input) {{ (void)input; return 0; }}\n\n"
                f"int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size) {{\n"
                f"    char *buf = malloc(size+1);\n"
                f"    if (!buf) return 0;\n"
                f"    memcpy(buf, data, size);\n"
                f"    buf[size]='\\0';\n"
                f"    {safe_target}(buf);\n"
                f"    free(buf);\n"
                f"    return 0;\n}}\n\n"
                f"#ifndef FUZZING_BUILD_MODE_UNSAFE_FOR_PRODUCTION\n"
                f"int main(int argc, char **argv) {{\n"
                f"    const char *input = argc > 1 ? argv[1] : \"\";\n"
                f"    printf(\"[harness] calling {safe_target} with %s\\n\", input);\n"
                f"    return {safe_target}(input);\n}}\n"
                f"#endif\n"
            )
        # rust / default
        return (
            f'// Fuzz harness for {target} — vtx-crs offensive+defensive.\n'
            f'// Run: cargo fuzz run harness_{safe_target}\n\n'
            f"use std::env;\n\n"
            f"fn target_fn(input: &str) {{\n"
            f"    // TODO: replace with actual call to {target} from {target_file}\n"
            f"    let _ = input;\n}}\n\n"
            f"fn main() {{\n"
            f"    let input = env::args().nth(1).unwrap_or_default();\n"
            f"    // Also support stdin for fuzzing\n"
            f"    let data = if input.is_empty() {{\n"
            f"        use std::io::Read;\n"
            f"        let mut s=String::new();\n"
            f"        let _= std::io::stdin().read_to_string(&mut s);\n"
            f"        s\n"
            f"    }} else {{ input }};\n"
            f"    target_fn(&data);\n"
            f"    println!(\"[harness] executed {target} with len={{}}\", data.len());\n}}\n"
        )
